CREATE TABLE governance_runs (
 id text PRIMARY KEY,
 kind text NOT NULL CHECK(kind IN ('profile','dataflow','workflow')),
 department_id text NOT NULL,
 actor_id text NOT NULL REFERENCES users(id),
 definition jsonb NOT NULL,
 state text NOT NULL CHECK(state IN ('queued','running','succeeded','failed','cancelled','interrupted')),
 retry_of text REFERENCES governance_runs(id),
 processed bigint NOT NULL DEFAULT 0 CHECK(processed>=0),
 result jsonb NOT NULL DEFAULT 'null',
 error_code text NOT NULL DEFAULT '',
 cancel_requested boolean NOT NULL DEFAULT false,
 lease_owner text NOT NULL DEFAULT '',
 lease_expires_at timestamptz NOT NULL DEFAULT '1970-01-01Z',
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 started_at timestamptz, finished_at timestamptz
);
CREATE INDEX governance_runs_queue ON governance_runs(created_at,id) WHERE state='queued';
CREATE INDEX governance_runs_department ON governance_runs(department_id,created_at DESC);
CREATE TABLE governance_run_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 run_id text NOT NULL REFERENCES governance_runs(id),
 node_id text NOT NULL DEFAULT '',
 code text NOT NULL,
 processed bigint NOT NULL DEFAULT 0,
 created_at timestamptz NOT NULL DEFAULT now()
);

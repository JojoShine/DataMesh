CREATE TABLE asset_feedback (
 id text PRIMARY KEY,
 reporter_id text NOT NULL REFERENCES users(id),
 reporter_department_id text NOT NULL,
 department_id text NOT NULL,
 workspace_id text NOT NULL DEFAULT '',
 resource_type text NOT NULL CHECK(resource_type IN ('raw_object','governed_dataset','table_resource','file_resource','api_resource')),
 resource_id text NOT NULL,
 contract_version integer NOT NULL CHECK(contract_version>0),
 directory_id text NOT NULL,
 resource_name text NOT NULL,
 category text NOT NULL CHECK(category IN ('quality','freshness','meaning','access')),
 title text NOT NULL,
 description text NOT NULL,
 fields jsonb NOT NULL DEFAULT '[]'::jsonb,
 run_id text NOT NULL DEFAULT '',
 issue_id text REFERENCES governance_quality_issues(id),
 state text NOT NULL DEFAULT 'submitted' CHECK(state IN ('submitted','in_progress','resolved')),
 response text NOT NULL DEFAULT '',
 version integer NOT NULL DEFAULT 1,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX asset_feedback_reporter ON asset_feedback(reporter_id,created_at DESC,id);
CREATE INDEX asset_feedback_inbox ON asset_feedback(department_id,workspace_id,state,created_at DESC,id);
CREATE TABLE asset_feedback_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 feedback_id text NOT NULL REFERENCES asset_feedback(id),
 action text NOT NULL,
 response text NOT NULL DEFAULT '',
 created_at timestamptz NOT NULL DEFAULT now()
);

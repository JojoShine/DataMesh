CREATE TABLE governance_quality_issues (
 id text PRIMARY KEY,
 department_id text NOT NULL,
 actor_id text NOT NULL REFERENCES users(id),
 assignee_id text NOT NULL REFERENCES users(id),
 run_id text NOT NULL UNIQUE REFERENCES governance_runs(id),
 flow_id text NOT NULL,
 flow_version integer NOT NULL CHECK(flow_version>0),
 due_at timestamptz NOT NULL,
 state text NOT NULL CHECK(state IN ('open','in_progress','retesting','closed')),
 version integer NOT NULL DEFAULT 1,
 retest_run_id text REFERENCES governance_runs(id),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 closed_at timestamptz,
 FOREIGN KEY(flow_id,flow_version) REFERENCES governance_versions(definition_id,version)
);
CREATE INDEX governance_quality_issues_owner ON governance_quality_issues(department_id,assignee_id,created_at DESC);
CREATE TABLE governance_quality_issue_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 issue_id text NOT NULL REFERENCES governance_quality_issues(id),
 actor_id text NOT NULL REFERENCES users(id),
 action text NOT NULL,
 note text NOT NULL DEFAULT '',
 run_id text REFERENCES governance_runs(id),
 created_at timestamptz NOT NULL DEFAULT now()
);

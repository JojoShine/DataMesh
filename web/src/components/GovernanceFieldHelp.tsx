function helpIcon(label:string){
 return <span className="governance-field-help" tabIndex={0} data-field-help={label} aria-description={`${label}的字段说明`} onClick={event=>{event.preventDefault();event.stopPropagation()}}><QuestionCircleOutlined aria-hidden="true"/></span>;
}

export function governanceFieldTooltip(label:string,explanation?:string):(TooltipProps & {icon:ReactElement})|undefined{
 const title=explanation??explanations[label];
 return title?{title,trigger:["hover","focus"],icon:helpIcon(label),styles:{root:{maxWidth:360}}}:undefined;
}

export function GovernanceFieldHelp({label,explanation}:{label:string;explanation?:string}){
 const props=governanceFieldTooltip(label,explanation);
 if(!props)return null;
 const {icon,...tooltip}=props;
 return <Tooltip {...tooltip}>{icon}</Tooltip>;
}
